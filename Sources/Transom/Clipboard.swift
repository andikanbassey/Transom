import AppKit
import Combine
import SwiftUI
import UniformTypeIdentifiers
import QuickLookThumbnailing

final class ClipboardStore: ObservableObject {
    @Published var clips: [Clip] = []
    // Filter state lives here so quick paste (⌘1–9) sees the same list the column shows.
    @Published var query = "" { didSet { fullHistoryDemandChanged(); pruneSelection() } }
    @Published var searching = false
    @Published var pinnedOnly = false { didSet { pruneSelection() } }
    /// Narrows the list to pins in one group (a name), to pins in no group (""), or nil for no group filter.
    @Published var groupFilter: String? { didSet { pruneSelection() } }
    @Published var filter = Category.Filter.all { didSet { fullHistoryDemandChanged(); pruneSelection() } }
    /// Library only: show clips copied from one app (see `appKey`). Nil shows every app.
    @Published var appFilter: String? { didSet { fullHistoryDemandChanged(); pruneSelection() } }
    /// Narrow the Library's clipboard page to a window of time.
    @Published var time = TimeFilter.any { didSet { fullHistoryDemandChanged(); pruneSelection() } }
    /// The item the keyboard has selected in the drawer (arrows move it, Return pastes it).
    @Published var cursor: UUID?
    /// The clip shown in full in place of the list, when clicking is set to expand.
    @Published var expanded: Clip?
    /// A filtered "Clear Unpinned" waiting for a yes, asked inside the window (a system alert would take focus and close the drawer).
    @Published var pendingClear: PendingClear?
    struct PendingClear: Equatable {
        var scope: String
        var count: Int
        /// Only items copied before this, for "Clear Unpinned Older Than…".
        var before: Date?
    }

    /// Select mode in the drawer: the items picked for a batch action, and the last one clicked (⇧-click selects from there).
    @Published var selecting = false
    @Published var selection = Set<UUID>()
    var selectionAnchor: UUID?
    /// "Delete n items?" waiting for a yes at the bottom of the panel, like `pendingClear`.
    @Published var pendingDelete: Set<UUID>?
    /// A group name being typed: for a new group holding `ids`, or a new name for `renaming`.
    struct GroupNaming: Equatable { var ids = Set<UUID>(); var renaming: String? }
    @Published var naming: GroupNaming?

    /// Picked items a new filter hides are let go, so a batch action never reaches items you cannot see.
    private func pruneSelection() {
        guard selecting, !selection.isEmpty else { return }
        let shown = Set(visible.map(\.id))
        if !selection.isSubset(of: shown) { selection.formIntersection(shown) }
    }

    /// Deleted items wait here for a few seconds so Undo can bring them back; only then are they really removed.
    struct PendingUndo: Equatable { var id = UUID(); var clips: [Clip] }
    @Published private(set) var undoable: PendingUndo?
    private var undoTimer: DispatchWorkItem?
    static let undoSeconds: TimeInterval = 6

    /// Months whose Markdown file needs rewriting, and the folder and file state the clips were loaded from.
    private var dirtyMonths = Set<String>()
    private var loadedFolder = ClipboardFolder.url.path
    private var loadedSignature = ""
    private var cancellable: AnyCancellable?
    private var lastCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var settings: SettingsValues { Settings.shared.v }
    private let confidentialTypes: Set<String> = ["org.nspasteboard.ConcealedType", "com.agilebits.onepassword"]
    private let transientTypes: Set<String> = ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    init(monitoring: Bool = true) {
        // History is read in the background: a month file that iCloud has moved out of this Mac can take a long time to
        // come back, and the app must still start (menu bar icon, drawer) while it does.
        load()
        cancellable = Settings.shared.$v.sink { [weak self] _ in
            DispatchQueue.main.async { self?.folderMayHaveChanged() }
        }
        NotificationCenter.default.addObserver(forName: NSApplication.willTerminateNotification, object: nil, queue: .main) { [weak self] _ in
            self?.commitPendingDelete(wait: true)
        }
        guard monitoring else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        Timer.scheduledTimer(withTimeInterval: 3600, repeats: true) { [weak self] _ in self?.trim() }
        // History changed on another Mac arrives as a changed file: pick it up within seconds.
        Timer.scheduledTimer(withTimeInterval: 10, repeats: true) { [weak self] _ in self?.refreshIfChanged() }
        // Every second, so an item goes at the moment its countdown reaches zero.
        Timer.scheduledTimer(withTimeInterval: 1, repeats: true) { [weak self] _ in self?.expireSensitive() }
    }

    /// Sensitive items are removed once they are old enough. They were never on disk, so there is nothing else to delete.
    func expireSensitive(now: Date = Date()) {
        guard clips.contains(where: { ($0.sensitiveExpiry ?? .distantFuture) <= now }) else { return }
        withAnimation(.easeOut(duration: 0.5)) {
            clips.removeAll { ($0.sensitiveExpiry ?? .distantFuture) <= now }
        }
    }

    // MARK: Storage

    private let diskQueue = DispatchQueue(label: "studioab.drawer.clipboard-disk", qos: .userInitiated)
    private let imageQueue = DispatchQueue(label: "studioab.drawer.clipboard-images", qos: .utility)
    @Published private(set) var loading = false
    private var isLoaded = false
    private var loadGeneration = 0
    private var loadedRetention = Settings.shared.v.retention
    private var previewsTidied = false
    /// Removed while a read was under way, so that read's older copy of the file must not bring them back.
    private var removedDuringLoad = Set<UUID>()

    // `clips` is a partial history: pins and the newest items. The rest stays on disk until something needs it.
    @Published private var deferred = DeferredHistory()
    private var fullHistoryHolders = Set<String>()
    private var whenFullyLoaded: [() -> Void] = []

    var deferredCount: Int { deferred.count }
    var totalCount: Int { clips.count + deferred.count }
    private var isFullyLoaded: Bool { isLoaded && !loading && deferred.isEmpty }
    private var wantsFullHistory: Bool { !fullHistoryHolders.isEmpty || !whenFullyLoaded.isEmpty || isFiltered || !query.isEmpty }

    /// Loads everything, then calls `done`. For operations that have to see every item.
    func requireFullHistory(then done: @escaping () -> Void) {
        if isFullyLoaded { done(); return }
        whenFullyLoaded.append(done)
        if !loading { load() }
    }

    /// A view that shows or searches the whole history (the Library, the search palette) holds it in memory while it is open.
    func holdFullHistory(_ holder: String) {
        guard fullHistoryHolders.insert(holder).inserted else { return }
        fullHistoryDemandChanged()
    }

    func releaseFullHistory(_ holder: String) {
        guard fullHistoryHolders.remove(holder) != nil else { return }
        // Views call this while they update; the list must not change under them.
        DispatchQueue.main.async { [weak self] in self?.dropOlderItems() }
    }

    private func fullHistoryDemandChanged() {
        if wantsFullHistory, !isFullyLoaded, !loading { load() }
    }

    /// Lets go of the text of items past the window. Clearing a search does not lead here directly, so typing the next search
    /// does not read everything again; it happens when the drawer closes or the next item is copied.
    private func dropOlderItems() {
        guard !wantsFullHistory, !loading else { return }
        let older = clips.filter { !$0.pinned && !$0.sensitive }.dropFirst(windowLimit)
        guard !older.isEmpty else { return }
        save()
        let lifetime = settings.retention.interval
        for clip in older { deferred.add(ClipRecord(clip), lifetime: lifetime) }
        let ids = Set(older.map(\.id))
        clips.removeAll { ids.contains($0.id) }
    }

    /// Reads the history from disk off the main thread, then merges it in. Reads and writes share one queue, so a load
    /// always sees a save that was started before it.
    private func load() {
        loadGeneration += 1
        let generation = loadGeneration
        let started = Date()
        let limit = wantsFullHistory ? nil : windowLimit
        let retention = settings.retention
        loading = true
        diskQueue.async { [weak self] in
            let read = Self.readHistory(limit: limit, lifetime: retention.interval, now: started)
            DispatchQueue.main.async {
                guard let self, generation == self.loadGeneration else { return }
                self.finishLoad(read, started: started, retention: retention)
            }
        }
    }

    private struct HistoryRead {
        var limit: Int?
        var clips: [Clip]
        var deferred: DeferredHistory
        var conflictedMonths: Set<String>
        var folder: String
        var signature: String
    }

    /// Runs on the disk queue. Only the month files holding a chosen item are read; the index answers for the others.
    private static func readHistory(limit: Int?, lifetime: TimeInterval?, now: Date) -> HistoryRead {
        ClipboardFolder.prepare()
        ClipboardFolder.pruneTombstones()
        // Taken before reading: a change that arrives during the read then still counts as new, and is picked up on the next check.
        let signature = ClipboardFolder.signature
        let dead = ClipboardFolder.tombstones()
        let files = ClipboardFolder.monthFiles()
        var index = ClipboardIndex.load()
        index.keep(only: files)

        var newest: [UUID: ClipRecord] = [:]
        var idsInFile: [URL: [UUID]] = [:]
        var filesPerMonth: [String: Int] = [:]
        for file in files {
            filesPerMonth[String(file.lastPathComponent.prefix(7)), default: 0] += 1
            autoreleasepool {
                let records = index.records(in: file)
                idsInFile[file] = records.map(\.id)
                for r in records where newest[r.id].map({ $0.modified < r.modified }) ?? true { newest[r.id] = r }
            }
        }
        index.saveIfChanged()

        let records = newest.values.filter { r in dead[r.id].map { $0 < r.modified } ?? true }
        let chosen = ClipRecord.selection(Array(records), limit: limit, cutoff: lifetime.map { now.addingTimeInterval(-$0) })
        var deferred = DeferredHistory()
        for r in records where !chosen.contains(r.id) { deferred.add(r, lifetime: lifetime) }

        var best: [UUID: Clip] = [:]
        for file in files where idsInFile[file]?.contains(where: chosen.contains) == true {
            autoreleasepool {
                guard let text = try? String(contentsOf: file, encoding: .utf8) else { return }
                for c in ClipHistoryFile.parse(text, including: chosen) where best[c.id].map({ $0.modified < c.modified }) ?? true { best[c.id] = c }
            }
        }
        let clips = best.values.filter { c in dead[c.id].map { $0 < c.modified } ?? true }
        // A month with more than one file has sync conflict copies: saving merges them into one.
        return HistoryRead(limit: limit, clips: clips, deferred: deferred, conflictedMonths: Set(filesPerMonth.filter { $0.value > 1 }.keys),
                           folder: ClipboardFolder.url.path, signature: signature)
    }

    private func finishLoad(_ read: HistoryRead, started: Date, retention: Retention) {
        // A copy, pin or deletion made during the read wins over the read's older snapshot.
        let changed = clips.filter { $0.modified >= started || $0.sensitive }
        let changedIDs = Set(changed.map(\.id))
        let waiting = Set(undoable?.clips.map(\.id) ?? [])
        clips = (changed + read.clips.filter { !changedIDs.contains($0.id) && !removedDuringLoad.contains($0.id) && !waiting.contains($0.id) })
            .sorted { $0.date > $1.date }
        removedDuringLoad = []
        deferred = read.deferred
        loadedRetention = retention
        dirtyMonths.formUnion(read.conflictedMonths)
        loadedFolder = read.folder
        loadedSignature = read.signature
        loading = false
        if !dirtyMonths.isEmpty { save() }

        let firstLoad = !isLoaded
        isLoaded = true
        if firstLoad { migrateLegacyHistory() }
        trim()
        if firstLoad { refetchMissingPreviews() }
        // Tidying goes by what the history refers to, so it must never run on a partial history.
        if isFullyLoaded, !previewsTidied {
            previewsTidied = true
            let snapshot = clips
            diskQueue.async { LinkPreviews.tidy(clips: snapshot) }
        }
        if isFullyLoaded {
            let waiting = whenFullyLoaded
            whenFullyLoaded = []
            waiting.forEach { $0() }
        }
        if loading { return }   // trim found more that expired and is already reading again
        let needsMore = !deferred.isEmpty && (wantsFullHistory || windowLimit > read.limit ?? 0)
        if needsMore || loadedRetention != settings.retention { load() } else { dropOlderItems() }
    }

    /// History from builds before Markdown storage lived in clips.json with pictures in an images folder.
    private func migrateLegacyHistory() {
        let fm = FileManager.default
        let legacy = supportDir.appendingPathComponent("clips.json")
        guard clips.isEmpty, let data = try? Data(contentsOf: legacy), let old = try? JSONDecoder().decode([Clip].self, from: data) else { return }
        let oldImages = supportDir.appendingPathComponent("images")
        for name in (try? fm.contentsOfDirectory(atPath: oldImages.path)) ?? [] {
            try? fm.copyItem(at: oldImages.appendingPathComponent(name), to: ClipboardFolder.images.appendingPathComponent(name))
        }
        clips = old
        for c in old { dirtyMonths.insert(ClipboardFolder.monthKey(c.date)) }
        save()
        try? fm.moveItem(at: legacy, to: supportDir.appendingPathComponent("clips.json.migrated"))
    }

    /// The storage folder moved (for example to iCloud Drive): bring the history along unless the new place has its own.
    private func folderMayHaveChanged() {
        let now = ClipboardFolder.url
        guard now.path != loadedFolder else {
            if loadedRetention != settings.retention, !loading { load() }
            return
        }
        let fm = FileManager.default
        try? fm.createDirectory(at: now, withIntermediateDirectories: true)
        let hasHistory = !(((try? fm.contentsOfDirectory(atPath: now.path)) ?? []).filter { $0.hasSuffix(".md") }.isEmpty)
        if !hasHistory {
            let old = URL(fileURLWithPath: loadedFolder)
            for item in (try? fm.contentsOfDirectory(at: old, includingPropertiesForKeys: nil)) ?? [] {
                try? fm.copyItem(at: item, to: now.appendingPathComponent(item.lastPathComponent))
            }
        }
        load()
    }

    /// Pick up history changed outside the app (another Mac through iCloud). Called when the drawer opens.
    func refreshIfChanged() {
        guard isLoaded, !loading, dirtyMonths.isEmpty, ClipboardFolder.signature != loadedSignature else { return }
        load()
    }

    func moveCursor(_ delta: Int) {
        let list = window
        guard !list.isEmpty else { return }
        if let current = list.firstIndex(where: { $0.id == cursor }) {
            cursor = list[min(max(current + delta, 0), list.count - 1)].id
        } else {
            cursor = list[delta > 0 ? 0 : list.count - 1].id
        }
    }

    var cursorClip: Clip? { visible.first { $0.id == cursor } }

    /// The clips the column shows: filtered, pinned first.
    var visible: [Clip] {
        var filtered = Self.filtered(clips, filter: filter, time: time, app: appFilter, pinnedOnly: pinnedOnly, query: query)
        if let g = groupFilter { filtered = filtered.filter { $0.pinned && ($0.pinGroup ?? "") == g } }
        return Self.pinnedByGroup(filtered.filter(\.pinned), groups: groups) + filtered.filter { !$0.pinned }
    }

    /// How many unpinned items the drawer draws before "Show older". Drawing the whole history made the drawer hold tens of
    /// megabytes of views for items nobody was looking at.
    static let windowStep = 200
    @Published var windowLimit = ClipboardStore.windowStep

    /// What the drawer draws: every pinned item, then the newest unpinned ones up to `windowLimit`.
    var window: [Clip] { Self.window(of: visible, limit: windowLimit) }
    /// Unpinned items still hidden behind "Show older".
    var hiddenCount: Int {
        max(0, visible.filter { !$0.pinned }.count - windowLimit) + (isFiltered || !query.isEmpty || pinnedOnly ? 0 : deferred.count)
    }
    func showOlder() { showNewest(windowLimit + Self.windowStep) }
    /// Widens the window to at least `count` items, reading them from disk if they are not in memory.
    func showNewest(_ count: Int) {
        windowLimit = max(windowLimit, count)
        if !deferred.isEmpty, !loading { load() }
    }
    func resetWindow() {
        if windowLimit != Self.windowStep { windowLimit = Self.windowStep }
        dropOlderItems()
    }

    /// Plain pins first, then each group in its order; within each, the order they came in.
    static func pinnedByGroup(_ pinned: [Clip], groups: [String]) -> [Clip] {
        let rank = Dictionary(groups.enumerated().map { ($1, $0 + 1) }, uniquingKeysWith: { a, _ in a })
        return pinned.enumerated().sorted { a, b in
            let ra = a.element.pinGroup.map { rank[$0] ?? Int.max } ?? 0
            let rb = b.element.pinGroup.map { rank[$0] ?? Int.max } ?? 0
            return ra != rb ? ra < rb : a.offset < b.offset
        }.map(\.element)
    }

    /// The window on its own, so it can be tested: `visible` is pinned first, then unpinned.
    static func window(of visible: [Clip], limit: Int) -> [Clip] {
        let pinned = visible.prefix { $0.pinned }
        let rest = visible.dropFirst(pinned.count)
        return Array(pinned) + Array(rest.prefix(limit))
    }

    /// The filtering behind `visible`, on its own so it can be tested.
    static func filtered(_ clips: [Clip], filter: Category.Filter, time: TimeFilter, app: String?, pinnedOnly: Bool, query: String,
                         now: Date = Date()) -> [Clip] {
        let q = query.trimmingCharacters(in: .whitespaces)
        return clips.filter { clip in
            clip.category.matches(filter)
                && time.includes(clip.date, now: now)
                && (app == nil || appKey(clip) == app)
                && (!pinnedOnly || clip.pinned)
                && (q.isEmpty || matches(clip, q))
        }
    }

    /// Search looks at the whole text (not only the first lines the title shows), link titles, file names and the app.
    /// A sensitive item is matched by its masked title only, never by what it hides.
    static func matches(_ clip: Clip, _ q: String) -> Bool {
        let opts: String.CompareOptions = [.caseInsensitive, .diacriticInsensitive]
        func has(_ s: String?) -> Bool { s.map { $0.range(of: q, options: opts) != nil } ?? false }
        if has(clip.title) || has(clip.sourceApp) { return true }
        guard !clip.sensitive else { return false }
        return has(clip.text) || has(clip.linkTitle) || clip.fileURLs.contains { has($0.lastPathComponent) }
    }

    /// How long a sensitive item stays in the list. It lives in memory only: it is never written to disk or synced.
    static let sensitiveLifetime: TimeInterval = 15 * 60

    /// Items bigger than this are not stored: they would bloat the history and slow every launch.
    static let maxTextBytes = 5_000_000
    static let maxImageBytes = 60_000_000

    private func poll() {
        // Until the history is in, leave the pasteboard alone: what is on it now is picked up as soon as it is.
        guard isLoaded else { return }
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        let s = settings
        let app = NSWorkspace.shared.frontmostApplication
        let isSelf = app?.bundleIdentifier == Bundle.main.bundleIdentifier
        let who = isSelf ? "Transom" : (app?.localizedName ?? "Unknown app")
        let log = CaptureLog.shared
        if AppModel.shared.standby { log.add(app: who, result: "Skipped: another Transom is active"); return }
        if s.paused { log.add(app: who, result: "Skipped: capture is paused"); return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        let concealed = !types.isDisjoint(with: confidentialTypes)
        // Concealed text can be kept, masked; anything else a password manager hides is skipped as before.
        let keepsAsSensitive = s.keepSensitiveMasked && pb.string(forType: .string) != nil
        if s.ignoreConfidential, concealed, !keepsAsSensitive { log.add(app: who, result: "Skipped: marked confidential"); return }
        if s.ignoreTransient, !types.isDisjoint(with: transientTypes) { log.add(app: who, result: "Skipped: marked transient"); return }
        if !isSelf, !Settings.shared.allows(bundleID: app?.bundleIdentifier) { log.add(app: who, result: "Skipped: app is not allowed"); return }
        var base = Clip(kind: .text)
        base.sourceApp = isSelf ? nil : app?.localizedName
        base.sourceBundleID = isSelf ? nil : app?.bundleIdentifier

        // Files first: Finder also puts the file name on the pasteboard as text.
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            var clip = base
            clip.kind = .file
            clip.paths = urls.map(\.path)
            insert(clip, replacing: { $0.paths == clip.paths })
            log.add(app: who, result: "Stored: \(urls.count == 1 ? "file" : "\(urls.count) files")")
        } else if let str = pb.string(forType: .string), !str.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard str.utf8.count <= Self.maxTextBytes else {
                log.add(app: who, result: "Skipped: text over \(Self.maxTextBytes / 1_000_000) MB")
                return
            }
            var clip = base
            clip.text = str
            clip.sensitive = s.keepSensitiveMasked && (concealed || SecretPatterns.looksSecret(str))
            if clip.sensitive { clip.sensitiveSince = Date() }
            clip.markdown = clip.sensitive ? nil : Self.richMarkdown(pb)
            let key = Clip.contentKey(str)
            insert(clip, replacing: { $0.kind == .text && Clip.contentKey($0.text ?? "") == key })
            log.add(app: who, result: clip.sensitive ? "Stored: sensitive text, masked and kept in memory only" : "Stored: text (\(str.count) characters)")
            if s.linkPreviews, clips.first?.category == .link, clips.first?.linkTitle == nil,
               let url = URL(string: str.trimmingCharacters(in: .whitespacesAndNewlines)), let id = clips.first?.id {
                fetchPreview(id: id, url: url)
            }
        } else if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff) {
            guard data.count <= Self.maxImageBytes else {
                log.add(app: who, result: "Skipped: image over \(Self.maxImageBytes / 1_000_000) MB")
                return
            }
            storeImage(data, alreadyPNG: pb.data(forType: .png) != nil, base: base, who: who)
        } else {
            log.add(app: who, result: "Skipped: nothing Transom can store (\(types.first ?? "empty"))")
        }
    }

    /// Encoding a large screenshot takes a moment: do it off the main thread, then add the item.
    /// Saves a copied picture. The same picture copied again (byte for byte, among the newest pictures) is not stored twice:
    /// the earlier item moves to the top and keeps its file.
    func storeImage(_ data: Data, alreadyPNG: Bool, base: Clip, who: String) {
        ClipboardFolder.prepare()
        let folder = ClipboardFolder.imageWriteFolder
        let candidates = clips.filter { $0.kind == .image }.prefix(60).compactMap(\.imageFile)
        imageQueue.async { [weak self] in
            // Some apps put JPEG (or HEIC) bytes on the pasteboard as public.png. Keep those bytes as they are, under the
            // extension they really have, so previews and pasting back see the right format.
            let real = Thumbs.pictureType(of: data)
            let keepAsIs = alreadyPNG && real != nil
            let ext = keepAsIs ? (real?.preferredFilenameExtension ?? "png") : "png"
            let name = UUID().uuidString + "." + ext
            let dest = folder.appendingPathComponent(name)
            guard let png = keepAsIs ? data : NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) else {
                DispatchQueue.main.async { CaptureLog.shared.add(app: who, result: "Failed: could not save the image") }
                return
            }
            var existing: String?
            for file in candidates {
                let url = ClipboardFolder.imageURL(file)
                // Same size first, and only files already on this Mac: never wait on an iCloud download for this.
                guard let size = (try? url.resourceValues(forKeys: [.fileSizeKey]))?.fileSize, size == png.count,
                      ClipboardFolder.isOnThisMac(url), let old = try? Data(contentsOf: url), old == png else { continue }
                existing = file
                break
            }
            let saved = existing != nil || (try? png.write(to: dest)) != nil
            DispatchQueue.main.async {
                guard saved else { CaptureLog.shared.add(app: who, result: "Failed: could not save the image"); return }
                var clip = base
                clip.kind = .image
                clip.imageFile = existing ?? name
                if let existing {
                    self?.insert(clip, replacing: { $0.kind == .image && $0.imageFile == existing })
                    CaptureLog.shared.add(app: who, result: "Stored: image (same as an earlier one, moved to the top)")
                } else {
                    self?.insert(clip, replacing: { _ in false })
                    CaptureLog.shared.add(app: who, result: "Stored: image")
                }
            }
        }
    }

    private func insert(_ clip: Clip, replacing match: (Clip) -> Bool) {
        var clip = clip
        // The same thing was copied long ago and is not in memory. It cannot be pinned (pins always are), so it can simply go.
        if !clip.sensitive, let identity = ClipRecord.identity(of: clip), let older = deferred.take(identity: identity) {
            dirtyMonths.insert(ClipboardFolder.monthKey(older.date))
            ClipboardFolder.addTombstone(older.id)
            if loading { removedDuringLoad.insert(older.id) }
        }
        if let i = clips.firstIndex(where: match) {
            clip.pinned = clips[i].pinned
            clip.group = clips[i].group
            clip.linkTitle = clips[i].linkTitle
            clip.linkImageFile = clips[i].linkImageFile
            dirtyMonths.insert(ClipboardFolder.monthKey(clips[i].date))
            // The older copy of the same thing is replaced, so other Macs must not bring it back.
            ClipboardFolder.addTombstone(clips[i].id)
            if loading { removedDuringLoad.insert(clips[i].id) }
            clips.remove(at: i)
        }
        clips.insert(clip, at: 0)
        if !clip.sensitive { dirtyMonths.insert(ClipboardFolder.monthKey(clip.date)) }
        trim()
        dropOlderItems()
    }

    /// Drop unpinned items past the retention window or the item limit.
    func trim() {
        // Something on disk has passed the period: read it so it can be archived like the rest.
        if !loading, let expiry = deferred.expiry, expiry <= Date() { load() }
        if let interval = settings.retention.interval {
            let cutoff = Date().addingTimeInterval(-interval)
            // A restored item keeps its old date but counts from when it was restored, so it is not expired again at once.
            removeAll(tombstone: true, archive: true) { !$0.pinned && max($0.date, $0.modified) < cutoff }
        }
        save()
        diskQueue.async { ClipboardArchive.purge() }
    }

    /// Brings archived items of a range back into the history. They get a new `modified` time so the deletion record
    /// that went with them no longer hides them. Calls `done` on the main thread with how many came back.
    func restoreArchived(_ range: ClipboardArchive.Range, done: @escaping (Int) -> Void) {
        diskQueue.async { [weak self] in
            let restored = ClipboardArchive.restore(range)
            DispatchQueue.main.async {
                guard let self else { return }
                let have = Set(self.clips.map(\.id))
                var back = restored.filter { !have.contains($0.id) }
                for i in back.indices { back[i].modified = Date() }
                for c in back { self.dirtyMonths.insert(ClipboardFolder.monthKey(c.date)) }
                self.clips = (self.clips + back).sorted { $0.date > $1.date }
                self.save()
                done(back.count)
            }
        }
    }

    // MARK: Link previews

    private func fetchPreview(id: UUID, url: URL) {
        var req = URLRequest(url: url, timeoutInterval: 8)
        req.setValue("Mozilla/5.0 (Macintosh; Intel Mac OS X 10_15) AppleWebKit/605.1.15 Transom", forHTTPHeaderField: "User-Agent")
        URLSession.shared.dataTask(with: req) { [weak self] data, _, _ in
            guard let self, let data else { return }
            let head = Data(data.prefix(300_000))
            guard let html = String(data: head, encoding: .utf8) ?? String(data: head, encoding: .isoLatin1) else { return }
            let title = Self.meta(html, "og:title") ?? Self.firstMatch(html, #"<title[^>]*>([^<]*)</title>"#)
            let imageRef = Self.meta(html, "og:image")
            let finish: (String?) -> Void = { imageFile in
                DispatchQueue.main.async {
                    guard let i = self.clips.firstIndex(where: { $0.id == id }) else { return }
                    self.clips[i].linkTitle = title.map(Self.decodeEntities)?.trimmingCharacters(in: .whitespacesAndNewlines)
                    self.clips[i].linkImageFile = imageFile
                    self.clips[i].modified = Date()
                    self.dirtyMonths.insert(ClipboardFolder.monthKey(self.clips[i].date))
                    self.save()
                }
            }
            guard let ref = imageRef, let imgURL = URL(string: Self.decodeEntities(ref), relativeTo: url)?.absoluteURL else { return finish(nil) }
            URLSession.shared.dataTask(with: imgURL) { imgData, _, _ in
                var name: String?
                if let imgData, let png = NSBitmapImageRep(data: imgData)?.representation(using: .png, properties: [:]) {
                    let n = UUID().uuidString + ".png"
                    LinkPreviews.prepare()
                    if (try? png.write(to: LinkPreviews.folder.appendingPathComponent(n))) != nil { name = n }
                }
                finish(name)
            }.resume()
        }.resume()
    }

    /// Covers are not synced, so a link copied on another Mac has none here yet: fetch the newest few again, under the
    /// same file names, without touching the history.
    private func refetchMissingPreviews() {
        guard settings.linkPreviews else { return }
        let missing = clips.filter { $0.category == .link && $0.linkImageFile != nil && $0.linkImageURL == nil }.prefix(30)
        for clip in missing {
            guard let name = clip.linkImageFile, let text = clip.text,
                  let url = URL(string: text.trimmingCharacters(in: .whitespacesAndNewlines)) else { continue }
            var req = URLRequest(url: url, timeoutInterval: 8)
            req.setValue("Mozilla/5.0 (Macintosh; Intel Mac OS X 10_15) AppleWebKit/605.1.15 Transom", forHTTPHeaderField: "User-Agent")
            URLSession.shared.dataTask(with: req) { data, _, _ in
                guard let data else { return }
                let head = Data(data.prefix(300_000))
                guard let html = String(data: head, encoding: .utf8) ?? String(data: head, encoding: .isoLatin1),
                      let ref = Self.meta(html, "og:image"),
                      let imgURL = URL(string: Self.decodeEntities(ref), relativeTo: url)?.absoluteURL else { return }
                URLSession.shared.dataTask(with: imgURL) { imgData, _, _ in
                    guard let imgData, let png = NSBitmapImageRep(data: imgData)?.representation(using: .png, properties: [:]) else { return }
                    LinkPreviews.prepare()
                    try? png.write(to: LinkPreviews.folder.appendingPathComponent(name))
                    DispatchQueue.main.async { self.objectWillChange.send() }
                }.resume()
            }.resume()
        }
    }

    private static func meta(_ html: String, _ key: String) -> String? {
        firstMatch(html, #"<meta[^>]+(?:property|name)=["']"# + key + #"["'][^>]*content=["']([^"']*)["']"#)
            ?? firstMatch(html, #"<meta[^>]+content=["']([^"']*)["'][^>]*(?:property|name)=["']"# + key + #"["']"#)
    }

    private static func firstMatch(_ text: String, _ pattern: String) -> String? {
        guard let re = try? NSRegularExpression(pattern: pattern, options: [.caseInsensitive]),
              let m = re.firstMatch(in: text, range: NSRange(text.startIndex..., in: text)),
              m.numberOfRanges > 1, let r = Range(m.range(at: 1), in: text) else { return nil }
        let value = String(text[r])
        return value.isEmpty ? nil : value
    }

    private static func decodeEntities(_ s: String) -> String {
        s.replacingOccurrences(of: "&amp;", with: "&").replacingOccurrences(of: "&quot;", with: "\"")
            .replacingOccurrences(of: "&#39;", with: "'").replacingOccurrences(of: "&#x27;", with: "'")
            .replacingOccurrences(of: "&lt;", with: "<").replacingOccurrences(of: "&gt;", with: ">")
    }

    // MARK: Actions

    func copy(_ clip: Clip, plain: Bool = false) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch clip.kind {
        case .text:
            if let md = clip.markdown, !plain, !clip.sensitive {
                pb.writeObjects([RichText.attributed(fromMarkdown: md)])
            } else {
                pb.setString(clip.text ?? "", forType: .string)
            }
        case .file: pb.writeObjects(clip.fileURLs as [NSURL])
        case .image:
            // Put the stored PNG back as it is. Handing macOS an NSImage instead makes it offer uncompressed TIFF,
            // so Finder pasted a 27 MB .tiff for a 2 MB screenshot.
            // The type follows the bytes: older versions saved JPEG data under .png names.
            if let data = clip.imageURL.flatMap({ try? Data(contentsOf: $0) }) ?? clip.heldImage {
                let type = Thumbs.pictureType(of: data).map { NSPasteboard.PasteboardType($0.identifier) } ?? .png
                pb.setData(data, forType: type)
            }
        }
        // Tells other clipboard managers (and Transom itself) not to record the copy again.
        if clip.sensitive { pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")) }
        lastCount = pb.changeCount
        if let i = clips.firstIndex(of: clip) {
            var moved = clips.remove(at: i)
            if !moved.sensitive { dirtyMonths.insert(ClipboardFolder.monthKey(moved.date)) }
            moved.date = Date()
            moved.modified = Date()
            dirtyMonths.insert(ClipboardFolder.monthKey(moved.date))
            clips.insert(moved, at: 0)
            save()
        }
    }

    func togglePin(_ clip: Clip) {
        guard let i = clips.firstIndex(of: clip), !clip.sensitive else { return }
        clips[i].pinned.toggle()
        if !clips[i].pinned { clips[i].group = nil }
        clips[i].modified = Date()
        dirtyMonths.insert(ClipboardFolder.monthKey(clips[i].date))
        save()
    }

    func delete(_ clip: Clip) { delete(ids: [clip.id]) }

    /// Deletes items with a few seconds to undo: they leave the list at once, and are removed for good (files, tombstones,
    /// a rewrite of their months) when the time is up, when something else is deleted, or when Transom quits.
    func delete(ids: Set<UUID>) {
        let doomed = clips.filter { ids.contains($0.id) }
        guard !doomed.isEmpty else { return }
        commitPendingDelete()
        clips.removeAll { ids.contains($0.id) }
        selection.subtract(ids)
        if expanded.map({ ids.contains($0.id) }) == true { expanded = nil }
        undoable = PendingUndo(clips: doomed)
        let work = DispatchWorkItem { [weak self] in self?.commitPendingDelete() }
        undoTimer = work
        DispatchQueue.main.asyncAfter(deadline: .now() + Self.undoSeconds, execute: work)
    }

    /// Brings back what the last delete took. Nothing has been written yet, so the items return exactly as they were.
    func undoDelete() {
        guard let pending = undoable else { return }
        undoTimer?.cancel()
        undoTimer = nil
        undoable = nil
        let ids = Set(pending.clips.map(\.id))
        clips = (clips.filter { !ids.contains($0.id) } + pending.clips).sorted { $0.date > $1.date }
    }

    /// Finishes a waiting delete now.
    func commitPendingDelete(wait: Bool = false) {
        guard let pending = undoable else { return }
        undoTimer?.cancel()
        undoTimer = nil
        undoable = nil
        ClipboardFolder.addTombstones(pending.clips.map(\.id))
        for clip in pending.clips { discardFiles(of: clip, tombstone: false) }
        save()
        if wait { diskQueue.sync {} }
    }

    func setPinned(_ pinned: Bool, ids: Set<UUID>) {
        for i in clips.indices where ids.contains(clips[i].id) && clips[i].pinned != pinned && !clips[i].sensitive {
            clips[i].pinned = pinned
            if !pinned { clips[i].group = nil }
            clips[i].modified = Date()
            dirtyMonths.insert(ClipboardFolder.monthKey(clips[i].date))
        }
        save()
    }

    // MARK: Groups

    /// Every group name: the saved order first, then any that arrived with items from another Mac.
    var groups: [String] {
        var names = Settings.shared.v.clipGroups
        for clip in clips { if let g = clip.pinGroup, !names.contains(g) { names.append(g) } }
        return names
    }

    /// Puts items in a group (pinning them, since groups hold pins) or, with nil, takes them out and leaves them pinned.
    func setGroup(_ name: String?, ids: Set<UUID>) {
        let name = name.map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }.flatMap { $0.isEmpty ? nil : $0 }
        if let name, !Settings.shared.v.clipGroups.contains(name) { Settings.shared.v.clipGroups.append(name) }
        for i in clips.indices where ids.contains(clips[i].id) && !clips[i].sensitive {
            guard clips[i].group != name || (name != nil && !clips[i].pinned) else { continue }
            clips[i].group = name
            if name != nil { clips[i].pinned = true }
            clips[i].modified = Date()
            dirtyMonths.insert(ClipboardFolder.monthKey(clips[i].date))
        }
        save()
    }

    /// Adds an empty group (it shows in menus and the Library until it is deleted).
    func addGroup(_ name: String) {
        let name = name.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !name.isEmpty, !groups.contains(name) else { return }
        Settings.shared.v.clipGroups.append(name)
    }

    func renameGroup(_ old: String, to new: String) {
        let new = new.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !new.isEmpty, new != old else { return }
        var names = groups
        if let i = names.firstIndex(of: old) { names[i] = new } else { names.append(new) }
        var seen = Set<String>()
        Settings.shared.v.clipGroups = names.filter { seen.insert($0).inserted }
        for i in clips.indices where clips[i].group == old {
            clips[i].group = new
            clips[i].modified = Date()
            dirtyMonths.insert(ClipboardFolder.monthKey(clips[i].date))
        }
        save()
    }

    /// Removes a group. Its items stay pinned, as plain pins.
    func deleteGroup(_ name: String) {
        Settings.shared.v.clipGroups.removeAll { $0 == name }
        setGroup(nil, ids: Set(clips.filter { $0.group == name }.map(\.id)))
    }

    /// Puts several items on the clipboard as one, oldest first (the order they were copied): text joined line by line, or
    /// all the files together. Pictures and sensitive items are left out of joined text. False when there was nothing to copy.
    @discardableResult
    func copyTogether(_ items: [Clip]) -> Bool {
        let pb = NSPasteboard.general
        let items = items.sorted { $0.date < $1.date }
        if !items.isEmpty, items.allSatisfy({ $0.kind == .file && !$0.sensitive }) {
            let files = items.flatMap(\.fileURLs)
            pb.clearContents()
            pb.writeObjects(files as [NSURL])
            return true
        }
        let texts = items.filter { $0.kind == .text && !$0.sensitive }.compactMap(\.text)
        guard !texts.isEmpty else { return false }
        pb.clearContents()
        pb.setString(texts.joined(separator: "\n"), forType: .string)
        return true
    }

    func clearUnpinned() {
        guard isFullyLoaded else { requireFullHistory { [weak self] in self?.clearUnpinned() }; return }
        removeAll(tombstone: true) { !$0.pinned }
        save()
    }

    /// True while an app, type or time filter narrows the list.
    var isFiltered: Bool { appFilter != nil || filter != .all || time != .any }

    /// The unpinned items the list shows right now: what "Clear Unpinned" clears while a filter is on.
    var unpinnedShown: [Clip] { visible.filter { !$0.pinned } }

    /// Clears the unpinned items that match the current filters, so with Claude selected only Claude's items go.
    /// With no filter on it is the same as `clearUnpinned()`. Pinned items always stay.
    func clearUnpinnedShown(before cutoff: Date? = nil) {
        guard isFullyLoaded else { requireFullHistory { [weak self] in self?.clearUnpinnedShown(before: cutoff) }; return }
        let ids = Set(unpinnedShown.filter { clip in cutoff.map { clip.date < $0 } ?? true }.map(\.id))
        guard !ids.isEmpty else { return }
        removeAll(tombstone: true) { ids.contains($0.id) }
        save()
    }

    /// What the menu item says it will clear: "Claude", "this selection" or nil for everything.
    var clearScopeName: String? {
        if let key = appFilter { return appsInHistory.first { $0.key == key }?.name ?? "this app" }
        return isFiltered ? "this selection" : nil
    }

    // MARK: Marking an item sensitive

    /// Makes an existing item sensitive: masked, removed from the history files (and from iCloud, through a tombstone) and the
    /// picture or link preview deleted, kept in memory only, and removed when its countdown ends. It gets a new id so
    /// nothing on disk or on another Mac can bring the old one back.
    func markSensitive(_ clip: Clip) {
        guard let i = clips.firstIndex(where: { $0.id == clip.id }), !clips[i].sensitive else { return }
        var c = clips[i]
        let noun: String
        switch c.category {
        case .link: noun = "link"
        case .image, .gif: noun = "image"
        case .video: noun = "video"
        case .audio, .pdf, .folder, .file: noun = "file"
        default: noun = c.kind == .text ? "item" : "file"
        }
        if c.kind == .image, let url = c.imageURL, let data = try? Data(contentsOf: url) { c.heldImage = data }
        remove(at: i, tombstone: true)       // deletes the picture and preview files and tombstones the id
        c.id = UUID()
        c.pinned = false
        c.imageFile = nil
        c.linkImageFile = nil
        c.linkTitle = nil
        c.markdown = nil
        c.sensitive = true
        c.sensitiveSince = Date()
        c.sensitiveAbout = noun
        c.modified = Date()
        clips.insert(c, at: min(i, clips.count))
        if expanded?.id == clip.id { expanded = nil }
        save()
    }

    /// Undoes `markSensitive` while the item is still in memory: it goes back into the history.
    func unmarkSensitive(_ clip: Clip) {
        guard let i = clips.firstIndex(where: { $0.id == clip.id }), clips[i].sensitive else { return }
        var c = clips[i]
        c.sensitive = false
        c.sensitiveSince = nil
        c.sensitiveAbout = nil
        c.modified = Date()
        if let data = c.heldImage {
            ClipboardFolder.prepare()
            let name = UUID().uuidString + ".png"
            if (try? data.write(to: ClipboardFolder.imageWriteFolder.appendingPathComponent(name))) != nil { c.imageFile = name }
            c.heldImage = nil
        }
        clips[i] = c
        dirtyMonths.insert(ClipboardFolder.monthKey(c.date))
        save()
    }

    func eraseAll() {
        guard isFullyLoaded else { requireFullHistory { [weak self] in self?.eraseAll() }; return }
        removeAll(tombstone: true) { _ in true }
        diskQueue.async { ClipboardIndex.erase() }
        // Nothing refers to this Mac's own pictures any more, so none are kept.
        for name in (try? FileManager.default.contentsOfDirectory(atPath: ClipboardFolder.localImages.path)) ?? [] {
            try? FileManager.default.removeItem(at: ClipboardFolder.localImages.appendingPathComponent(name))
        }
        save()
    }

    private func remove(at i: Int, tombstone: Bool = false) {
        discardFiles(of: clips[i], tombstone: tombstone)
        clips.remove(at: i)
    }

    /// Removes every item that matches in one pass. Removing them one by one copied the whole history each time, which made
    /// clearing or trimming thousands of items take many seconds.
    /// With `archive`, the items go to `ClipboardArchive` (pictures included) instead of being lost; sensitive ones never do.
    private func removeAll(tombstone: Bool = false, archive: Bool = false, where match: (Clip) -> Bool) {
        let doomed = clips.filter(match)
        guard !doomed.isEmpty else { return }
        if tombstone { ClipboardFolder.addTombstones(doomed.map(\.id)) }
        let kept = archive ? doomed.filter { !$0.sensitive } : []
        if !kept.isEmpty { diskQueue.async { ClipboardArchive.store(kept) } }
        for clip in doomed { discardFiles(of: clip, tombstone: false, keepPicture: archive && !clip.sensitive) }
        clips.removeAll(where: match)
    }

    /// What deleting an item leaves behind to clean up: its tombstone, its picture and link preview, and a rewrite of its month.
    private func discardFiles(of clip: Clip, tombstone: Bool, keepPicture: Bool = false) {
        if tombstone { ClipboardFolder.addTombstone(clip.id) }
        if loading { removedDuringLoad.insert(clip.id) }
        if !keepPicture, let file = clip.imageFile {
            // Clearing history deletes the picture too, wherever it is kept.
            try? FileManager.default.removeItem(at: ClipboardFolder.images.appendingPathComponent(file))
            try? FileManager.default.removeItem(at: ClipboardFolder.localImages.appendingPathComponent(file))
        }
        if let file = clip.linkImageFile { try? FileManager.default.removeItem(at: LinkPreviews.folder.appendingPathComponent(file)) }
        dirtyMonths.insert(ClipboardFolder.monthKey(clip.date))
    }

    /// Rewrite only the months that changed. Each month is merged with what is on disk first, so another Mac's
    /// additions and changes (arriving through iCloud) are kept: newest change per item wins, deletions stay deleted.
    private func save() {
        guard !dirtyMonths.isEmpty else { return }
        let months = dirtyMonths
        let snapshot = clips.filter { !$0.sensitive }
        dirtyMonths = []
        diskQueue.async { [weak self] in
            Self.write(months: months, clips: snapshot)
            let signature = ClipboardFolder.signature
            DispatchQueue.main.async { self?.loadedSignature = signature }
        }
    }

    /// Rewrites the given months, each merged with what is on disk first (see `save`). Runs on the disk queue.
    private static func write(months: Set<String>, clips: [Clip]) {
        ClipboardFolder.prepare()
        let dead = ClipboardFolder.tombstones()
        let mine = Dictionary(clips.map { ($0.id, $0) }, uniquingKeysWith: { a, _ in a })
        let byMonth = Dictionary(grouping: clips, by: { ClipboardFolder.monthKey($0.date) })
        for month in months {
            let canonical = ClipboardFolder.fileURL(month: month)
            let files = ClipboardFolder.files(forMonth: month)
            var merged: [UUID: Clip] = [:]
            for file in files {
                guard let text = try? String(contentsOf: file, encoding: .utf8) else { continue }
                for c in ClipHistoryFile.parse(text) {
                    // Copied again on this Mac, so it now belongs to a later month.
                    if let m = mine[c.id], ClipboardFolder.monthKey(m.date) != month { continue }
                    if let old = merged[c.id], old.modified >= c.modified { continue }
                    merged[c.id] = c
                }
            }
            for c in byMonth[month] ?? [] {
                if let old = merged[c.id], old.modified > c.modified { continue }
                merged[c.id] = c
            }
            let items = merged.values.filter { c in dead[c.id].map { $0 < c.modified } ?? true }
            if items.isEmpty {
                for f in files { try? FileManager.default.removeItem(at: f) }
            } else {
                try? ClipHistoryFile.render(month: month, clips: Array(items)).write(to: canonical, atomically: true, encoding: .utf8)
                // Compared by real location: a folder reached through a symlink (such as /tmp) lists its files under the resolved path,
                // and deleting what looks like another copy would delete the file just written.
                for f in files where !ClipboardFolder.sameFile(f, canonical) { try? FileManager.default.removeItem(at: f) }
            }
        }
    }

    /// Markdown for the copied text when it has formatting; rich text first, then HTML.
    private static func richMarkdown(_ pb: NSPasteboard) -> String? {
        if let rtf = pb.data(forType: .rtf), let attr = NSAttributedString(rtf: rtf, documentAttributes: nil) {
            return RichText.markdown(from: attr)
        }
        if let html = pb.data(forType: .html), html.count < 200_000,
           let attr = try? NSAttributedString(data: html, options: [.documentType: NSAttributedString.DocumentType.html,
                                                                    .characterEncoding: String.Encoding.utf8.rawValue],
                                              documentAttributes: nil) {
            return RichText.markdown(from: attr)
        }
        return nil
    }
}

// MARK: - Cover art

extension ClipboardStore {
    /// What identifies the app a clip came from: its bundle id, or its name when there is none.
    static func appKey(_ clip: Clip) -> String? { clip.sourceBundleID ?? clip.sourceApp }

    /// The apps in the history, most used first, with a name, an icon key and a count, for the Library's App filter.
    var appsInHistory: [(key: String, name: String, bundle: String?, count: Int)] {
        var seen = deferred.apps
        for c in clips {
            guard let key = Self.appKey(c) else { continue }
            var entry = seen[key] ?? (c.sourceApp ?? key, c.sourceBundleID, 0)
            entry.count += 1
            seen[key] = entry
        }
        return seen.map { (key: $0.key, name: $0.value.name, bundle: $0.value.bundle, count: $0.value.count) }
            .sorted { $0.count != $1.count ? $0.count > $1.count : $0.name.localizedCaseInsensitiveCompare($1.name) == .orderedAscending }
    }
}

